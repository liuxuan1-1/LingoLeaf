export function localizeMessage(message: string, language: UiLanguage): string {
  if (language === 'zh-CN') return message;
  const t = createTranslator(language);
  let result = message.replace(/^无法读取 (.+)。原文件已保留，请检查权限或从备份恢复。$/, (_match, file: string) =>
    t('无法读取 {file}。原文件已保留，请检查权限或从备份恢复。', 'Cannot read {file}. The original is preserved; check permissions or restore a backup.', { file }));
  for (const [chinese, english] of [...MESSAGE_PAIRS].sort((a, b) => b[0].length - a[0].length))
    result = result.split(chinese).join(t(chinese, english));
  return result;
}
